import { chromium, webkit } from "playwright";
import assert from "node:assert/strict";
const url = process.env.LEO_TEST_URL || "http://localhost:5174";
for (const engine of [chromium, webkit]) {
  const browser = await engine.launch(engine === chromium ? { channel: "chrome" } : {});
  const page = await browser.newPage({ viewport: { width: 1180, height: 740 }, hasTouch: true });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`${url}/#sk`);
  await page.evaluate(() => {
    localStorage.removeItem("leo-muted");
    window.__clips = [];
    document.querySelector("#leo-voice").addEventListener("playing", (event) => {
      window.__clips.push({ id: event.target.dataset.clip, at: performance.now() });
    });
  });
  await page.locator('[data-machine="screw"]').tap();
  await page.waitForFunction(() => document.querySelector("#leo-voice").currentTime > 0.05);
  await page.locator(".model-stage").tap();
  await page.waitForTimeout(1100);
  assert.equal(await page.locator("#leo-voice").getAttribute("data-clip"), "screw-1", "touch does not replace the sentence");
  assert.ok(await page.locator("#leo-voice").evaluate((audio) => !audio.paused && audio.currentTime > 0.5));
  await page.locator("#leo-voice").evaluate((audio) => { audio.currentTime = audio.duration - 0.1; });
  await page.waitForFunction(() => window.__clips.some((clip) => clip.id === "screw-1-result"));
  assert.deepEqual(await page.evaluate(() => window.__clips.map((clip) => clip.id).filter((id, i, ids) => i === 0 || id !== ids[i - 1])), ["screw-1", "screw-1-result"]);
  await page.locator(".action-button").tap();
  await page.waitForTimeout(250);
  assert.equal(await page.locator("#leo-voice").getAttribute("data-clip"), "screw-1-result", "playing again does not restart the discovery");
  await page.locator('[data-step="1"]').tap();
  await page.waitForFunction(() => document.querySelector("#leo-voice").currentTime > 0.05);
  const stage = await page.locator(".model-stage").boundingBox();
  await page.mouse.move(stage.x + stage.width / 2, stage.y + stage.height / 2);
  await page.mouse.down();
  await page.mouse.move(stage.x + stage.width / 2 + 70, stage.y + stage.height / 2 + 30, { steps: 6 });
  await page.locator("#leo-voice").evaluate((audio) => { audio.currentTime = audio.duration - 0.1; });
  await page.waitForTimeout(950);
  assert.equal(await page.locator("#leo-voice").getAttribute("data-clip"), "screw-2", "Leo waits for the held model");
  await page.mouse.up();
  await page.waitForFunction(() => document.querySelector("#leo-voice").dataset.clip === "screw-2-result");
  await page.locator('[data-step="2"]').tap();
  await page.waitForFunction(() => document.querySelector("#leo-voice").currentTime > 0.05);
  await page.locator(".action-button").tap();
  await page.locator(".leo-button").tap();
  await page.waitForTimeout(2600);
  assert.ok(await page.locator("#leo-voice").evaluate((audio) => audio.paused), "explicit pause stays quiet");
  await page.locator(".home-button").tap();
  assert.equal(await page.locator(".machine-choice").count(), 6);
  await page.waitForTimeout(800);
  assert.equal(await page.locator("#leo-voice").getAttribute("data-clip"), "hello", "old discoveries cannot leak through navigation");

  await page.goto(`${url}/#sk/knight/1`);
  const arm = await page.locator(".drawing-parts").innerHTML();
  await page.locator(".model-stage").focus();
  await page.keyboard.press("ArrowRight");
  await page.waitForTimeout(180);
  assert.notEqual(await page.locator(".drawing-parts").innerHTML(), arm, "arrow keys bend the arm rather than an unused crank");
  await page.goto(`${url}/#sk/cart/4`);
  const parked = await page.locator(".drawing-parts").getAttribute("transform");
  await page.locator(".model-stage").focus();
  await page.keyboard.press("ArrowRight");
  await page.waitForTimeout(180);
  assert.notEqual(await page.locator(".drawing-parts").getAttribute("transform"), parked, "arrow key releases the cart");

  await page.goto(`${url}/#sk/screw/4`);
  await page.locator(".action-button").tap();
  await page.waitForFunction(() => Number(document.querySelector(".machine-art").dataset.rock) > 1);
  assert.ok(await page.locator(".drawing-parts").getAttribute("transform"));
  await page.waitForFunction(() => document.querySelector(".model-stage").dataset.settled === "true");
  assert.equal(await page.locator(".machine-art").getAttribute("data-rock"), "0");
  const still = await page.locator(".drawing-parts").innerHTML();
  await page.waitForTimeout(500);
  assert.equal(await page.locator(".drawing-parts").innerHTML(), still, "failed attempt never loops by itself");

  await page.goto(`${url}/#sk/cart/3`);
  await page.locator(".action-button").tap();
  await page.waitForFunction(() => document.querySelector(".model-stage").dataset.settled === "true");
  const tension = () => page.locator('[data-part="springcoil"]').getAttribute("data-tension");
  assert.ok(Number(await tension()) > 0.45 && Number(await tension()) < 0.6);
  assert.notEqual(await page.locator("#leo-voice").getAttribute("data-clip"), "cart-3-result", "half a turn is not a fully wound spring");
  await page.locator(".action-button").tap();
  await page.waitForFunction(() => Number(document.querySelector('[data-part="springcoil"]').dataset.tension) > 0.98);
  await page.waitForFunction(() => document.querySelector("#leo-voice").dataset.clip === "cart-3-result");
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto(`${url}/#en/screw/4`);
  await page.locator(".action-button").tap();
  await page.waitForTimeout(150);
  assert.equal(await page.locator(".machine-art").getAttribute("data-rock"), "0", "reduced motion stays grounded without rocking");
  await page.locator(".home-button").tap();
  assert.equal(await page.locator(".machine-choice").count(), 6);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log(`${engine.name()}: speech sequencing, quiet pause, Home, failed lift and spring tension passed`);
}
